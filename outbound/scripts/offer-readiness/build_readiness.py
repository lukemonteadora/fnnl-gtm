"""Regenerates the read-only Offer Readiness views from client-profile.yaml
(outbound/reference/offer-readiness.md). Never hand-edit the outputs; change the profile
(or run offer_approval.py) and re-run.

    python outbound/scripts/offer-readiness/build_readiness.py <client-dir>            # write the views
    python outbound/scripts/offer-readiness/build_readiness.py <client-dir> --check    # exit 1 if the views on disk are stale

Outputs:
    offers/_readiness-board.md          one screen, one row per offer (mirrors deduped)
    offers/<offer-folder>/readiness.md  one page per offer (folder offers/offer-<rank>-*,
                                        or offers/offer-<rank> when none exists)

Reads (never writes): client-profile.yaml, campaigns/*/leads.verified.csv (the `offer`
column, to list each offer's campaigns), client-asks.md (outbound/reference/client-messages.md:
each pending offer's 48h clock runs from the newest `### Sent` entry carrying `[offer-<rank>]`,
else the `Sent:` line of the current message), and
each sample file's existence. Caps come only from their existing homes:
qualification.free_unit_cap_per_week and, where the client supplies the deliverable,
offer.scale_review.confirmed_capacity_per_week.

A profile with no Aaron-lane offer yields no views ("not applicable"); --check exits 0.
"""
import datetime, glob, hashlib, os, sys
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from readiness_common import EVID, offers_with_mirrors, drift, campaigns_by_offer, ask_state, comparable  # noqa: E402

TODAY = datetime.date.today()
NUDGE_HOURS = 48  # GUESS default (offer-readiness.md)


def cap_text(b, profile):
    """The weekly cap, read only from its existing homes (no new cap field)."""
    mode = b.get("delivery_mode")
    if mode in ("client_input", "client_delivers") or (mode is None and b.get("lead_magnet_yes_honored_by") == "client"):
        sr = b.get("scale_review") or ((profile.get("offer") or {}).get("scale_review")) or {}
        n = sr.get("confirmed_capacity_per_week") if isinstance(sr, dict) else None
        return f"{n} a week (client-confirmed)" if n else "not set: client capacity unknown (ask it)"
    q = b.get("qualification")
    n = q.get("free_unit_cap_per_week") if isinstance(q, dict) else None
    return f"{n} free units a week" if n else "none (requested, not trimmed)"


def folder_for(client_dir, rank):
    hits = sorted(glob.glob(os.path.join(client_dir, "offers", f"offer-{rank}-*")))
    return hits[0] if hits else os.path.join(client_dir, "offers", f"offer-{rank}")


def start_rail(ok):
    return {"not_needed": "clear (agency-honored, no approval exists)",
            "yes": "clear (client said yes)",
            "pending": "BLOCKED: client_ok pending (drafting continues)",
            "no": "NEVER BUILT: client said no"}.get(ok, f"unknown value {ok!r}")


def short_name(offer):
    return str(offer).split(" for ")[0].split(" with ")[0].rstrip(".")


def next_action(b, client, ask, sent_on, sample_exists):
    s, ok = b.get("sample") or {}, b.get("lead_magnet_client_ok")
    if ok == "pending":
        if not ask or not ask.startswith("sent"):
            return f"Send the current message in client-asks.md (asks {client} for this offer)", "operator"
        age = (TODAY - sent_on).days * 24 if sent_on else 0
        if age >= NUDGE_HOURS:
            return f"Nudge {client} (ask sent {age // 24} days ago, no answer)", "operator"
        return f"Wait for {client}'s answer (inside the 48h window)", "operator"
    if ok == "no":
        return "Nothing: this arm is never built", "none"
    if not s:
        return "Build the sample in Phase 4 step 2 (on a verified row)", "Claude (Phase 4)"
    if sample_exists and not s.get("reviewed_by"):
        return "Review the sample, then mark reviewed", "operator"
    if s.get("missing"):
        first = str(s["missing"][0])
        return first, first.split(":")[0] if ":" in first else "see missing"
    return "Ready on the approval rail; other Phase 4 gates still apply", "none"


def build(client_dir):
    prof_path = os.path.join(client_dir, "client-profile.yaml")
    raw = open(prof_path, "rb").read()
    src = hashlib.sha1(raw).hexdigest()[:12]
    profile = yaml.safe_load(raw.decode("utf-8")) or {}
    ranks = offers_with_mirrors(profile)
    if not ranks:
        return None, profile
    client = (profile.get("business") or {}).get("name") or os.path.basename(os.path.normpath(client_dir))
    camps = campaigns_by_offer(client_dir, set(ranks))
    msg_ask, _ = ask_state(client_dir)  # the current message, for the board header
    head = (f"<!-- GENERATED by outbound/scripts/offer-readiness/build_readiness.py from client-profile.yaml (sha1 {src}). "
            f"Read-only view: do not hand-edit. Change the profile or run offer_approval.py, then regenerate. -->\n")
    files, rows, nudges, drifts = {}, [], [], []
    for rank in sorted(ranks):
        mirrors = ranks[rank]
        b = mirrors[0][1]
        d = drift(mirrors)
        drifts += d
        s = b.get("sample") or {}
        c = b.get("capacity") or {}
        ok = b.get("lead_magnet_client_ok")
        ask, sent_on = ask_state(client_dir, rank)  # per offer: the message that carried its ask
        sample_exists = bool(s.get("path")) and os.path.exists(os.path.join(client_dir, s["path"]))
        # Derived, never stored: no block = not built yet; no path = none; file + reviewer = reviewed; file only = DRAFT.
        if not s:
            sample_txt = "not built yet (Phase 4 step 2)"
        elif not s.get("path"):
            sample_txt = "none"
        elif not sample_exists:
            sample_txt = "FILE MISSING"
        else:
            sample_txt = "reviewed" if s.get("reviewed_by") else "DRAFT (unreviewed)"
        if ok == "pending" and s.get("path"):
            sample_txt += "; offer blocked on client"
        na, owner = next_action(b, client, ask, sent_on, sample_exists)
        cap = cap_text(b, profile)
        cl = ", ".join(f"{slug} ({n})" for slug, n in camps.get(rank, [])) or "none yet"
        missing = [str(m) for m in (s.get("missing") or [])]
        rows.append(f"| {rank} | {b.get('lead_magnet')} | {b.get('delivery_mode')} | {ok} | "
                    f"{start_rail(ok).split(':')[0].split(' (')[0]} | {sample_txt} | {c.get('expected_yeses_per_week', 'not estimated')} | "
                    f"{cap} | {len(missing)}: {'; '.join(missing)} | {na} | {owner} |")
        if ok == "pending":
            if sent_on and (TODAY - sent_on).days * 24 >= NUDGE_HOURS:
                nudges.append(f"- Offer {rank}: pending {(TODAY - sent_on).days} days. Nudge draft for the operator: \"Hi, any word from "
                              f"{client} on {short_name(b.get('lead_magnet'))}? Even a rough yes or no helps us plan the launch.\"")
            else:
                nudges.append(f"- Offer {rank}: pending, and the ask is {ask or 'not drafted'}, so no clock is running yet. "
                              f"Nothing sends on silence.")
        page = [head, f"# Offer {rank} readiness: {b.get('lead_magnet')}\n",
                f"Regenerated {TODAY.isoformat()} from {len(mirrors)} mirrors in client-profile.yaml ({', '.join(w for w, _ in mirrors)}).\n",
                "## Approval (source of truth: lead_magnet_yes_honored_by and lead_magnet_client_ok)\n",
                f"- Who honors a yes: **{b.get('lead_magnet_yes_honored_by')}** (delivery mode: {b.get('delivery_mode')})",
                f"- Client OK: **{ok}**; by: {b.get(EVID[0])}; at: {b.get(EVID[1])}; evidence: {b.get(EVID[2])}",
                f"- What the client must do: {b.get('lead_magnet_client_dependency')}",
                f"- Start rail per arm: {start_rail(ok)}",
                f"- Arm status: {b.get('status', 'primary')}; campaigns: {cl}\n",
                "## Capacity (GUESS where labelled)\n"]
        page += [f"- {k}: {v}" for k, v in c.items()] or ["- not estimated yet"]
        page += [f"- cap in force: {cap}"]
        page += ["", "## Sample\n", f"- Stage: {sample_txt}", f"- Account: {s.get('account')}",
                 f"- Prepared: {s.get('prepared')}", f"- Reviewed by: {s.get('reviewed_by')}",
                 f"- Provisional: {s.get('provisional_reason')}", f"- File: {s.get('path')}", "",
                 "## Missing, and from whom\n"] + ([f"- {m}" for m in missing] or ["- None recorded."]) + [
                 "", "## Next action\n", f"- {na} (owner: {owner})", "",
                 "## Mirror check\n", f"- {'All mirrors agree.' if not d else 'DRIFT: ' + ', '.join(d)}", ""]
        files[os.path.join(folder_for(client_dir, rank), "readiness.md")] = "\n".join(page)

    board = [head, f"# Offer readiness board: {client}\n",
             f"Regenerated {TODAY.isoformat()}. One row per offer; each row is read from client-profile.yaml "
             f"(mirrors deduped and checked). Current client message: {msg_ask or 'none'}.\n",
             "| # | Offer | Delivery mode | Client OK | Start (approval rail) | Sample | Expected yeses/week | Send cap | Missing | Next action | Owner |",
             "|---|---|---|---|---|---|---|---|---|---|---|"] + rows + [
             "", "## Pending approvals and nudges (48h, GUESS default; silence never sends)\n"] + (nudges or ["- None."]) + [
             "", "## Mirror drift\n", "- None." if not drifts else "- " + "\n- ".join(drifts), ""]
    files[os.path.join(client_dir, "offers", "_readiness-board.md")] = "\n".join(board)
    return files, profile


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    if sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        return
    client_dir = sys.argv[1]
    check = "--check" in sys.argv
    files, _ = build(client_dir)
    if files is None:
        print("not applicable: no Aaron-lane offer in client-profile.yaml; no views")
        return
    stale = []
    for path, text in files.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if check:
            if comparable(old) != comparable(text):
                stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8", newline="\n").write(text)
    if check:
        print("views current" if not stale else "STALE: " + ", ".join(stale))
        sys.exit(1 if stale else 0)
    print(f"wrote {len(files)} views; see offers/_readiness-board.md")


if __name__ == "__main__":
    main()
