"""Writes each wave campaign's reply notes as ONE `## Notes` block and compiles
profiles/<slug>/reply-playbook.md (outbound/reference/offer-readiness.md, decision 5).

    python outbound/scripts/offer-readiness/build_reply_playbook.py <client-dir> [--check]

Where each campaign's Notes block goes:
    campaigns/<slug>/interested-reply.md   when it exists (Phase 4 step 3 wrote it): the
                                           generated lines are inserted into its `## Notes`
                                           section between two sentinel lines, replacing any
                                           earlier generated lines; a missing `## Notes`
                                           section is appended at the end
    offers/reply-notes/<slug>.md           otherwise (staged until Phase 4 writes the file;
                                           this script never creates interested-reply.md, and
                                           deletes the staged file once the block has moved in)

`lifecycle_docx_presentation.ps1` turns every `## ` heading other than When to Use, Notes,
Call Script and Confirmation Page into an email step, and prints Notes lines as plain text.
So the block adds no other heading and uses plain `- Label: text` lines, no bold labels.

The content comes from two places only:
  - client-profile.yaml: the offer line, the approval rail, campaign row counts;
  - offers/reply-notes.json (per client, gitignored with the profile): every line that is
    client-specific or prospect-facing. Its prospect-facing lines (the yes-reply, FAQ
    answers, any over-cap reply) are Aaron's words from a fresh /ask-aaron call, recorded
    word for word; the yes-reply is his delivery frame DR. See offer-readiness.md for the
    schema. Strings may use ${var} slots filled per campaign (string.Template).
A wave campaign with no entry in reply-notes.json gets a "Needs Aaron" placeholder, never
house-written copy. Nothing here sends anything or configures the reply inbox on the
sending platform: the playbook is a paste view for the operator, and reply agents stay the
operator's to set up (widened only at 80% of the first 50 drafts, offer-readiness.md,
decision 6).
"""
import csv, hashlib, json, os, re, sys
from string import Template
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from readiness_common import offers_with_mirrors, campaigns_by_offer, eol_of_text, comparable  # noqa: E402

START = "- Offer Readiness notes start (generated by build_reply_playbook.py from client-profile.yaml and offers/reply-notes.json; regenerate, do not hand-edit)."
END = "- Offer Readiness notes end."


def fill(text, vars_):
    return Template(str(text)).safe_substitute(vars_)


def start_rail(ok, client):
    return {"pending": f"BLOCKED until {client} says yes (lead_magnet_client_ok pending; drafted, Start held)",
            "not_needed": "clear on the approval rail (other Phase 4 gates still apply)",
            "yes": "clear on the approval rail (client said yes)",
            "no": "never built (client said no)"}.get(ok, f"unknown value {ok!r}")


def notes_lines(slug, rank, b, n_rows, client, data):
    camp = (data.get("campaigns") or {}).get(slug)
    ok = b.get("lead_magnet_client_ok")
    lines = [f"- Offer {rank}, in one line: {b.get('lead_magnet')}."
             + (f" Vertical: {camp['vars']['vertical']}." if camp and camp.get("vars", {}).get("vertical") else ""),
             f"- Start (approval rail): {start_rail(ok, client)}. Campaign-ready rows: {n_rows}."]
    off = (data.get("offers") or {}).get(str(rank)) if camp else None
    if not camp or not off:
        return lines + [
            "- Needs Aaron: no reply notes are recorded for this campaign yet. The yes-reply, FAQ answers and any over-cap "
            "reply come from a fresh /ask-aaron call, recorded word for word in offers/reply-notes.json; nothing house-written "
            "is filled in here.",
            "- Needs recording: what counts as a yes, turnaround, the fulfillment handoff, the call brief, never-claim and "
            "hand-to-human triggers (from the offer block and the Aaron campaign plan)."]
    v = dict(off.get("vars") or {})
    v.update(camp.get("vars") or {})
    for k, t in (off.get("vars") or {}).items():  # offer-level slots may use campaign slots
        v[k] = fill(t, {**v, **(camp.get("vars") or {})})
    f = lambda t: fill(t, v)  # noqa: E731
    link = camp.get("link_status") or off.get("link_status")
    if link:
        lines.append(f"- Link or document status: {f(link)}")
    lines.append(f"- What counts as a yes: {f(off.get('what_counts_as_yes') or data.get('what_counts_as_yes', 'Needs recording.'))}")
    lines.append(f"- The yes-reply (Aaron's delivery frame DR, word for word; only the bracket changes): {f(off['yes_reply'])}"
                 if off.get("yes_reply") else "- The yes-reply: Needs Aaron (his delivery frame DR, recorded word for word).")
    for key, label in (("need", "What we need from the prospect"), ("turnaround", "Turnaround")):
        if off.get(key):
            lines.append(f"- {label}: {f(off[key])}")
    if off.get("handoff"):
        lines.append("- Fulfillment handoff: " + " ".join(f"({i}) {f(s)}" for i, s in enumerate(off["handoff"], 1)))
    if off.get("call_brief"):
        lines.append(f"- Call brief (for whoever takes the call): {f(off['call_brief'])}")
    faq = off.get("faq") or []
    if faq:
        lines.append(f"- FAQ and objections ({f(data.get('faq_source', 'Aaron'))}; frame in brackets; only the slots are filled here). "
                     f"{f(data.get('faq_rule', ''))}".rstrip())
        lines += [f"- {f(q)} {f(a)}" for q, a in faq]
    if off.get("over_cap") or data.get("over_cap"):
        lines.append(f"- If a weekly cap is reached: {f(off.get('over_cap') or data['over_cap'])}")
    lines += [f"- Never claim: {f(x)}" for x in (data.get("never_claim") or [])]
    lines += [f"- Hand to a human when: {f(x)}" for x in (data.get("handoff_triggers") or [])]
    return lines


def upsert_notes(path, body_lines):
    raw = open(path, encoding="utf-8", newline="").read()
    eol = eol_of_text(raw)
    lines = raw.splitlines()
    block = [START] + body_lines + [END]
    if START in lines and END in lines:
        s, e = lines.index(START), lines.index(END)
        lines[s:e + 1] = block
    else:
        h = next((i for i, l in enumerate(lines) if re.match(r"^##\s+Notes\s*$", l)), None)
        if h is None:
            while lines and not lines[-1].strip():
                lines.pop()
            lines += ["", "## Notes", ""] + block
        else:
            e = next((i for i in range(h + 1, len(lines)) if re.match(r"^##\s+", lines[i])), len(lines))
            while e > h + 1 and not lines[e - 1].strip():
                e -= 1
            lines[e:e] = ([""] if lines[e - 1].strip() and e - 1 != h else []) + block
    return eol.join(lines) + eol


def build(client_dir):
    prof = os.path.join(client_dir, "client-profile.yaml")
    raw = open(prof, "rb").read()
    profile = yaml.safe_load(raw.decode("utf-8")) or {}
    ranks = offers_with_mirrors(profile)
    if not ranks:
        return None
    client = (profile.get("business") or {}).get("name") or os.path.basename(os.path.normpath(client_dir))
    dpath = os.path.join(client_dir, "offers", "reply-notes.json")
    data = json.load(open(dpath, encoding="utf-8")) if os.path.exists(dpath) else {}
    wave = {slug: rank for rank, lst in campaigns_by_offer(client_dir, set(ranks)).items() for slug, _ in lst}
    for slug, c in (data.get("campaigns") or {}).items():
        wave.setdefault(slug, int(c["offer"]))
    outputs, rows, bodies = {}, [], []
    for slug in sorted(wave, key=lambda s: (wave[s], list((data.get("campaigns") or {}).keys()).index(s)
                                             if s in (data.get("campaigns") or {}) else 999, s)):
        rank = wave[slug]
        if rank not in ranks:
            sys.exit(f"reply-notes.json: campaign {slug} names offer {rank}, which is not in the profile")
        b = ranks[rank][0][1]
        f = os.path.join(client_dir, "campaigns", slug, "leads.verified.csv")
        n = sum(1 for _ in csv.DictReader(open(f, encoding="utf-8-sig"))) if os.path.exists(f) else 0
        body = notes_lines(slug, rank, b, n, client, data)
        ir = os.path.join(client_dir, "campaigns", slug, "interested-reply.md")
        if os.path.exists(ir):
            outputs[ir] = upsert_notes(ir, body)
            where = f"campaigns/{slug}/interested-reply.md"
            staged = os.path.join(client_dir, "offers", "reply-notes", f"{slug}.md")
            if os.path.exists(staged):
                outputs[staged] = None  # superseded by the block now inside interested-reply.md
        else:
            outputs[os.path.join(client_dir, "offers", "reply-notes", f"{slug}.md")] = "\n".join(["## Notes", "", START] + body + [END]) + "\n"
            where = f"offers/reply-notes/{slug}.md (staged; interested-reply.md not written yet)"
        bodies.append(f"## SDR section: {slug}\n\nNotes block: {where}\n\n" + "\n".join(body) + "\n")
        camp = (data.get("campaigns") or {}).get(slug) or {}
        after = ((data.get("offers") or {}).get(str(rank)) or {}).get("after_yes", "needs recording") if camp else "needs Aaron"
        thing = (camp.get("vars") or {}).get("thing", b.get("lead_magnet"))
        rows.append(f"| {slug} | {rank} | {thing} | {after} | {b.get('lead_magnet_client_ok')} | {n} |")
    src = hashlib.sha1(raw).hexdigest()[:12]
    wave_label = f"wave {data['wave']}, {data.get('version', 'v1')}" if data.get("wave") else "current wave"
    head = [
        f"<!-- GENERATED by outbound/scripts/offer-readiness/build_reply_playbook.py (profile sha1 {src}). Read-only compiled view of every campaign's reply notes: do not hand-edit. -->", "",
        f"# Reply playbook: {client} ({wave_label})", "",
        "**What this is.** Every wave campaign's interested-reply notes in one place, formatted so the operator can paste it into a reply agent in the reply inbox on the sending platform. Nothing here configures that inbox; reply agents and AI reply features stay the operator's to set up and switch on.", "",
        "**Mode: start in draft-and-approve.** The agent (or the SDR) drafts and a human approves every send. The agent is widened only once 80% of its first 50 drafts went out with light or no edits (decision 6 in `outbound/reference/offer-readiness.md`), and fully automatic sending always needs the operator's explicit decision.", ""]
    if data.get("playbook_status"):
        head += [f"**Status.** {data['playbook_status']}", ""]
    head += ["## Overview", "",
             "| Campaign | Offer | What they get | After the yes | Client OK | Campaign-ready rows |",
             "|---|---|---|---|---|---:|"] + rows + [""]
    outputs[os.path.join(client_dir, "reply-playbook.md")] = "\n".join(head) + "\n" + "\n---\n\n".join(bodies)
    return outputs


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    if sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        return
    client_dir, check = sys.argv[1], "--check" in sys.argv
    outputs = build(client_dir)
    if outputs is None:
        print("not applicable: no Aaron-lane offer in client-profile.yaml; no reply notes")
        return
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
        if text is None:  # a staged fragment superseded by interested-reply.md
            if check:
                stale.append(path)
            else:
                os.remove(path)
            continue
        if check:
            if comparable(old) != comparable(text):
                stale.append(path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8", newline="").write(text)
    if check:
        print("reply notes current" if not stale else "STALE: " + ", ".join(stale))
        sys.exit(1 if stale else 0)
    print(f"notes blocks: {sum(1 for v in outputs.values() if v is not None) - 1}; playbook written")


if __name__ == "__main__":
    main()
